// Helper to insert icon with sizing and ARIA
function icon(name, options = {}) {
  const svg = Icons[name];
  if (!svg) return '';
  
  const size = options.size || '1em';
  const cls = options.class || '';
  const label = options.label || '';
  
  const aria = label ? `aria-label="${label}" role="img"` : 'aria-hidden="true"';
  const style = `width:${size};height:${size};display:inline-block;vertical-align:middle;flex-shrink:0;`;
  
  return svg.replace('<svg', `<svg class="${cls}" style="${style}" ${aria}`);
}

